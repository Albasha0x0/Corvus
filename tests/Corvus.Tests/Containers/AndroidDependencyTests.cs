using System.Text;
using Corvus.Core;
using Corvus.Services.Analysis;
using Corvus.Services.Analysis.Dependencies;
using Corvus.Tests.NativeFormats;

namespace Corvus.Tests;

/// <summary>summarize_file view=dependencies on Android packages: Java libraries, native libraries, .NET and Il2Cpp code.</summary>
public sealed class AndroidDependencyTests : IDisposable
{
    private readonly TempDir _dir = new();
    private readonly AssemblyWorkspace _workspace = new(new ServerOptions());

    public void Dispose()
    {
        _workspace.Dispose();
        _dir.Dispose();
    }

    internal static byte[] Text(string s) => Encoding.UTF8.GetBytes(s);

    /// <summary>An ARM64 shared library whose read-only data holds <paramref name="strings"/>, NUL-terminated.</summary>
    internal static byte[] NativeLibrary(params string[] strings) => new ElfWriter
    {
        Machine = ElfWriter.EmAarch64, Is64 = true, Type = 3, Text = [0xC0, 0x03, 0x5F, 0xD6], Hash = ElfWriter.HashKind.None,
        DataSectionName = ".rodata", Data = [.. strings.SelectMany(s => Encoding.ASCII.GetBytes(s + "\0")), .. new byte[16]],
    }.Build();

    /// <summary>A Java and native app: Maven properties, AndroidX and module version files, one library for two ABIs.</summary>
    internal static byte[] JavaApp()
    {
        var native = NativeLibrary("OpenSSL 3.0.13 30 Jan 2024", " deflate 1.3.1 Copyright 1995-2024 Jean-loup Gailly and Mark Adler ");
        return AndroidSamples.Apk(30,
            ("classes.dex", [0x64, 0x65, 0x78, 0x0A, 0x30, 0x33, 0x35, 0x00]),
            ("META-INF/MANIFEST.MF", Text("Manifest-Version: 1.0\nCreated-By: Android Gradle 8.5.0\n")),
            ("META-INF/maven/com.squareup.okhttp3/okhttp/pom.properties", Text("#Generated by Maven\nversion=4.12.0\ngroupId=com.squareup.okhttp3\nartifactId=okhttp\n")),
            ("META-INF/androidx.core_core.version", Text("1.9.0\n")),
            ("META-INF/kotlinx_coroutines_core.version", Text("1.7.3\n")),
            ("META-INF/androidx.annotation_annotation.version", Text("task ':annotation:writeVersionFile' property 'version'\n")),
            ("lib/arm64-v8a/libnative.so", native),
            ("lib/armeabi-v7a/libnative.so", native));
    }

    private DependencyFacts Facts(string name, byte[] apk)
    {
        var path = _dir.File(name);
        File.WriteAllBytes(path, apk);
        return Assert.IsType<DependencyFacts>(new InspectionService(_workspace).Summarize(null, path, default, new FileViewOptions("dependencies")).Views["dependencies"].Detail);
    }

    [Fact]
    public void Maven_properties_and_androidx_version_files_give_maven_purls_and_a_module_file_stays_without_one()
    {
        var facts = Facts("app.apk", JavaApp());
        Assert.Equal(("com.example.app", "1.2", "application"), (facts.Subject!.Name, facts.Subject.Version, facts.Subject.Type));
        var maven = facts.All.Where(c => c.Ecosystem == "maven").ToDictionary(c => c.Name);
        Assert.Equal("pkg:maven/com.squareup.okhttp3/okhttp@4.12.0", maven["com.squareup.okhttp3:okhttp"].Purl);
        Assert.Equal(["META-INF/maven/com.squareup.okhttp3/okhttp/pom.properties"], maven["com.squareup.okhttp3:okhttp"].Locations);
        Assert.Equal(("1.9.0", "pkg:maven/androidx.core/core@1.9.0"), (maven["androidx.core:core"].Version, maven["androidx.core:core"].Purl));
        Assert.Equal(("1.7.3", null), (maven["kotlinx_coroutines_core"].Version, maven["kotlinx_coroutines_core"].Purl));
        Assert.Equal((null, null, false), (maven["androidx.annotation:annotation"].Version, maven["androidx.annotation:annotation"].Purl, maven["androidx.annotation:annotation"].VersionKnown));
        Assert.Equal(["META-INF/androidx.annotation_annotation.version"], maven["androidx.annotation:annotation"].Locations);
        DependencyInventoryTests.AssertValid(CycloneDx.Write(facts, "app.apk", new string('0', 64), "1.0.0", DateTimeOffset.UnixEpoch, Guid.Empty));
    }

    [Fact]
    public void A_native_library_is_listed_once_with_its_abis_and_the_versions_compiled_into_it()
    {
        var facts = Facts("app.apk", JavaApp());
        var library = Assert.Single(facts.All, c => c.Name == "libnative.so");
        Assert.Equal(("native", null, null), (library.Ecosystem, library.Version, library.Purl));
        Assert.Equal(["lib/arm64-v8a/libnative.so", "lib/armeabi-v7a/libnative.so"], library.Locations);
        var openssl = Assert.Single(facts.All, c => c.Name == "OpenSSL");
        Assert.Equal(("3.0.13", "binary-analysis"), (openssl.Version, openssl.Technique));
        Assert.Equal(["lib/arm64-v8a/libnative.so", "lib/armeabi-v7a/libnative.so"], openssl.Locations);
        Assert.Equal("1.3.1", Assert.Single(facts.All, c => c.Name == "zlib").Version);
    }

    [Fact]
    public void A_dotnet_for_android_app_lists_its_compressed_assemblies_by_informational_version()
    {
        var json = File.ReadAllBytes(RealPackages.Lib("Newtonsoft.Json", "13.0.1", "netstandard2.0", "Newtonsoft.Json.dll"));
        var facts = Facts("dotnet.apk", AndroidSamples.Apk(30, ("assemblies/Newtonsoft.Json.dll", ContainerFixtures.Xalz(json))));
        var c = Assert.Single(facts.All, c => c.Name == "Newtonsoft.Json");
        Assert.Equal(("13.0.1", "pkg:nuget/Newtonsoft.Json@13.0.1"), (c.Version, c.Purl));
        Assert.Equal("com.example.app", facts.Subject!.Name);
    }

    [Fact]
    public void An_il2cpp_apk_lists_unity_and_the_games_assemblies_from_its_metadata()
    {
        var metadata = new Il2CppMetadataWriter().Assembly("Assembly-CSharp", "0.0.0.0").Assembly("mscorlib", "4.0.0.0").Assembly("Newtonsoft.Json", "13.0.0.0").Build();
        // globalgamemanagers keeps the Unity version as a NUL-terminated string at offset 20.
        byte[] managers = [.. new byte[20], .. Encoding.ASCII.GetBytes("2021.3.45f1"), 0, .. new byte[64]];
        var facts = Facts("game.apk", AndroidSamples.Apk(30,
            ("assets/bin/Data/Managed/Metadata/global-metadata.dat", metadata), ("assets/bin/Data/globalgamemanagers", managers),
            ("lib/arm64-v8a/libil2cpp.so", NativeLibrary("il2cpp")), ("lib/arm64-v8a/libunity.so", NativeLibrary("unity"))));
        Assert.Equal("com.example.app", facts.Subject!.Name);
        var unity = Assert.Single(facts.All, c => c.Name == "Unity");
        Assert.Equal(("2021.3.45f1", "pkg:generic/unity@2021.3.45f1"), (unity.Version, unity.Purl));
        Assert.Equal(("13.0.0.0", null), Assert.Single(facts.All, c => c.Name == "Newtonsoft.Json") is var j ? (j.AssemblyVersion, j.Version) : default);
        Assert.Contains(facts.All, c => c.Name == "libil2cpp.so");
    }

    /// <summary>A split set: base.apk with the Java libraries and a .NET assembly, config.arm64_v8a.apk with the native library.</summary>
    private static byte[] SplitSet()
    {
        var json = File.ReadAllBytes(RealPackages.Lib("Newtonsoft.Json", "13.0.1", "netstandard2.0", "Newtonsoft.Json.dll"));
        var native = NativeLibrary("OpenSSL 3.0.13 30 Jan 2024");
        return ContainerFixtures.Zip(
            ("base.apk", AndroidSamples.Apk(30,
                ("META-INF/MANIFEST.MF", Text("Manifest-Version: 1.0\n")),
                ("META-INF/maven/com.squareup.okhttp3/okhttp/pom.properties", Text("version=4.12.0\ngroupId=com.squareup.okhttp3\nartifactId=okhttp\n")),
                ("assemblies/Newtonsoft.Json.dll", ContainerFixtures.Xalz(json)))),
            ("config.arm64_v8a.apk", ContainerFixtures.Zip(("lib/arm64-v8a/libnative.so", native))));
    }

    [Theory]
    [InlineData("app.xapk")]
    [InlineData("app.apks")]
    [InlineData("app.apkm")]
    public void A_split_set_is_one_app_with_each_split_as_a_location(string name)
    {
        var facts = Facts(name, SplitSet());
        Assert.Equal(("com.example.app", "1.2"), (facts.Subject!.Name, facts.Subject.Version));
        var okhttp = Assert.Single(facts.All, c => c.Name == "com.squareup.okhttp3:okhttp");
        Assert.Equal(["base.apk!/META-INF/maven/com.squareup.okhttp3/okhttp/pom.properties"], okhttp.Locations);
        Assert.Equal(["config.arm64_v8a.apk!/lib/arm64-v8a/libnative.so"], Assert.Single(facts.All, c => c.Name == "libnative.so").Locations);
        Assert.Equal("3.0.13", Assert.Single(facts.All, c => c.Name == "OpenSSL").Version);
        Assert.Equal("pkg:nuget/Newtonsoft.Json@13.0.1", Assert.Single(facts.All, c => c.Name == "Newtonsoft.Json").Purl);
        DependencyInventoryTests.AssertValid(CycloneDx.Write(facts, name, new string('0', 64), "1.0.0", DateTimeOffset.UnixEpoch, Guid.Empty));
    }

    [Fact]
    public void An_il2cpp_split_set_lists_unity_from_the_metadata_in_its_base_apk()
    {
        var metadata = new Il2CppMetadataWriter().Assembly("Assembly-CSharp", "0.0.0.0").Assembly("mscorlib", "4.0.0.0").Build();
        byte[] managers = [.. new byte[20], .. Encoding.ASCII.GetBytes("2021.3.45f1"), 0, .. new byte[64]];
        var facts = Facts("game.xapk", ContainerFixtures.Zip(
            ("base.apk", AndroidSamples.Apk(30,
                ("assets/bin/Data/Managed/Metadata/global-metadata.dat", metadata), ("assets/bin/Data/globalgamemanagers", managers))),
            ("config.arm64_v8a.apk", ContainerFixtures.Zip(("lib/arm64-v8a/libil2cpp.so", NativeLibrary("il2cpp"))))));
        Assert.Equal("2021.3.45f1", Assert.Single(facts.All, c => c.Name == "Unity").Version);
        Assert.Equal(["config.arm64_v8a.apk!/lib/arm64-v8a/libil2cpp.so"], Assert.Single(facts.All, c => c.Name == "libil2cpp.so").Locations);
    }
}
