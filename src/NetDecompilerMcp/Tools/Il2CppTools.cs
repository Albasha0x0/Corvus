using System.ComponentModel;
using System.Text;
using dnlib.DotNet;
using ModelContextProtocol.Server;
using NetDecompilerMcp.Core;
using NetDecompilerMcp.Services;
using static NetDecompilerMcp.Tools.ToolSupport;

namespace NetDecompilerMcp.Tools;

[McpServerToolType]
public sealed class Il2CppTools(AssemblyWorkspace workspace, Il2CppService il2cpp, Il2CppExporter exporter, OutputPager pager)
{
    [McpServerTool(Name = "get_il2cpp_info", Title = "Il2Cpp addresses and offsets", ReadOnly = true, OpenWorld = false)]
    [Description("For Il2CppDumper/Cpp2IL dummy DLLs: native addresses (RVA, VA, file offset, vtable slot) of a method or of every method in a type, plus field offsets and metadata tokens. Use them to jump to the function in IDA/Ghidra.")]
    public Task<string> GetIl2CppInfo(
        [Description("Type or method. " + SymbolDescription)] string symbol,
        [Description(AssemblyFilterDescription)] string? assembly = null,
        CancellationToken cancellationToken = default) => Read(workspace, () =>
    {
        var sb = new StringBuilder();
        bool any = false;
        var symbols = SymbolResolver.Resolve(workspace, assembly, symbol);
        // A symbol may match in both managed and Il2Cpp dummy assemblies; only the dummy side has addresses.
        var withMetadata = symbols.Where(s => il2cpp.GetIndex(s.Assembly).Count > 0).ToList();
        if (withMetadata.Count > 0 && withMetadata.Count < symbols.Count)
        {
            sb.AppendLine($"({symbols.Count - withMetadata.Count} match(es) in assemblies without Il2Cpp metadata skipped: " +
                          string.Join(", ", symbols.Except(withMetadata).Select(s => s.Assembly.Id).Distinct().Take(5)) + ")");
            sb.AppendLine();
            symbols = withMetadata;
        }
        foreach (var sym in symbols.Take(25))
        {
            sb.AppendLine($"{sym.Kind} {sym.Label}  [{sym.Assembly.Id}] {Format.Token(sym.Member)}");
            foreach (var a in Il2CppService.GetAttributes(sym.Member)) { sb.AppendLine("  " + a); any = true; }
            if (sym.Member is TypeDef t)
            {
                foreach (var f in t.Fields)
                    if (Il2CppService.GetAttributes(f) is { Count: > 0 } fa) { sb.AppendLine($"  field  {Format.Field(f)}  {string.Join(" ", fa)}"); any = true; }
                foreach (var m in t.Methods)
                    if (Il2CppService.GetAttributes(m) is { Count: > 0 } ma) { sb.AppendLine($"  method {Format.Method(m, withModifiers: false)}  {string.Join(" ", ma)}"); any = true; }
            }
            sb.AppendLine();
        }
        if (!any)
            sb.AppendLine("No Il2Cpp attributes found. This needs a dummy DLL generated by Il2CppDumper or Cpp2IL (with attribute injection).");
        return pager.Page(sb.ToString());
    }, cancellationToken);

    [McpServerTool(Name = "export_il2cpp_symbols", Title = "Export IDA/Ghidra scripts", OpenWorld = false)]
    [Description("Export Il2Cpp dummy-DLL metadata for native analysis: an IDA Python script and a Ghidra script that create every function, name it Namespace.Type$$Method " +
                 "and comment it with the managed signature, a C header with struct layouts at the dumped field offsets (the IDA script imports it), and an Il2CppDumper-style script.json. " +
                 "Addresses are RVAs added to the database's image base, so the scripts work on any load address.")]
    public Task<string> ExportIl2CppSymbols(
        [Description("Output directory.")] string outputDirectory,
        [Description("Formats, comma-separated: ida, ghidra, header, json, or all (default).")] string formats = "all",
        [Description("Base name for the generated files (default il2cpp).")] string baseName = "il2cpp",
        [Description(AssemblyFilterDescription)] string? assembly = null,
        CancellationToken cancellationToken = default) => Read(workspace, () =>
    {
        var result = exporter.Export(workspace.Scope(assembly), outputDirectory, formats, baseName, cancellationToken);
        return $"Exported {result.Methods} functions and {result.Structs} struct layouts:\n  " + string.Join("\n  ", result.Files) +
               "\nIDA: File > Script file... on the _ida.py. Ghidra: run the _ghidra.py from the Script Manager; import the .h with File > Parse C Source.";
    }, cancellationToken);

    [McpServerTool(Name = "find_method_by_address", Title = "Native address to method", ReadOnly = true, OpenWorld = false)]
    [Description("Map a native address from IDA/Ghidra/a crash log back to the managed method using Il2Cpp [Address] attributes. Reports exact function starts, or the closest preceding method when the address is inside a function.")]
    public Task<string> FindMethodByAddress(
        [Description("Address in hex as IDA/Ghidra show it: '0x1A2B3C', '1A2B3C', '1A2B3Ch' or '00000001`8001A2B3'. Prefix 'd:' for decimal.")] string address,
        [Description("Which attribute value to compare: rva, va, offset, or auto (all three).")] string kind = "auto",
        [Description(AssemblyFilterDescription)] string? assembly = null,
        CancellationToken cancellationToken = default) => Read(workspace, () =>
    {
        var value = Il2CppService.ParseAddress(address) ?? throw new ToolError($"'{address}' is not a valid hex address.");
        var matches = il2cpp.FindByAddress(value, kind, workspace.Scope(assembly));
        if (matches.Count == 0) return $"No method found at or before 0x{value:X}.";
        var sb = new StringBuilder($"Address 0x{value:X}:\n");
        foreach (var m in matches)
            sb.AppendLine($"  [{m.Field.ToUpperInvariant()}] {m.Relation}: {Format.MemberLabel(m.Entry.Method)}  (start 0x{m.Start:X})  [{m.Entry.Assembly.Id}] {Format.Token(m.Entry.Method)}");
        return sb.ToString();
    }, cancellationToken);
}
