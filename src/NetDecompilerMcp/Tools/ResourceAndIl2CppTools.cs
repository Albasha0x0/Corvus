[McpServerToolType]
public sealed class ResourceTools(AssemblyWorkspace workspace, ResourceService resources, OutputPager pager)
{
    [McpServerTool(Name = "list_resources", ReadOnly = true)]
    [Description("List manifest resources (embedded files, .resources containers with entry counts, linked resources).")]
    public Task<string> ListResources(
        [Description("Assembly id, name or path.")] string assembly,
        CancellationToken cancellationToken = default) => Read(workspace, () =>
    {
        var asm = workspace.Get(assembly);
        var list = resources.List(asm);
        if (list.Count == 0) return $"{asm.Id} has no resources.";
        var sb = new StringBuilder($"{asm.Id}: {Plural(list.Count, "resource")}\n");
        foreach (var r in list)
            sb.AppendLine($"  {r.Name}  [{r.Kind}{(r.Size is { } s ? $", {s:N0} bytes" : "")}{(r.EntryCount is { } n ? $", {n} entries" : "")}{(r.IsPublic ? "" : ", private")}]");
        return sb.ToString();
    }, cancellationToken);

    [McpServerTool(Name = "get_resource", ReadOnly = true)]
    [Description("Read a resource: text is returned as text, binary as a hex preview, .resources containers as an entry list (pass entry to read one). Pass savePath to extract raw bytes to disk (images, bundles, etc.).")]
    public Task<string> GetResource(
        [Description("Assembly id, name or path.")] string assembly,
        [Description("Resource name as shown by list_resources.")] string name,
        [Description("Entry name inside a .resources container.")] string? entry = null,
        [Description("If set, write the raw bytes of the resource (or entry) to this file path.")] string? savePath = null,
        [Description(OffsetDescription)] int offset = 0,
        [Description(MaxCharsDescription)] int? maxChars = null,
        CancellationToken cancellationToken = default) => Read(workspace, () =>
    {
        var asm = workspace.Get(assembly);
        return pager.Page(resources.Get(asm, name, entry, savePath), offset, maxChars);
    }, cancellationToken);
}

[McpServerToolType]
public sealed class Il2CppTools(AssemblyWorkspace workspace, Il2CppService il2cpp, OutputPager pager)
{
    [McpServerTool(Name = "get_il2cpp_info", ReadOnly = true)]
    [Description("For Il2CppDumper/Cpp2IL dummy DLLs: native addresses (RVA, VA, file offset, vtable slot) of a method or of every method in a type, plus field offsets and metadata tokens. Use these to jump to the function in IDA/Ghidra.")]
    public Task<string> GetIl2CppInfo(
        [Description("Type or method. " + SymbolDescription)] string symbol,
        [Description(AssemblyDescription)] string? assembly = null,
        CancellationToken cancellationToken = default) => Read(workspace, () =>
    {
        var all = SymbolResolver.Resolve(workspace, assembly, symbol);
        var sb = new StringBuilder();
        foreach (var sym in all.Take(25))
        {
            sb.AppendLine($"{sym.Kind} {sym.Label}  [{sym.Assembly.Id}] {Format.Token(sym.Member)}");
            AppendAttrs(sb, sym.Member, "  ");
            if (sym.Member is TypeDef t)
            {
                foreach (var f in t.Fields)
                {
                    var a = Il2CppService.GetAttributes(f);
                    if (a.Count > 0) sb.AppendLine($"  field  {Format.Field(f)}  {string.Join(" ", a)}");
                }
                foreach (var m in t.Methods)
                {
                    var a = Il2CppService.GetAttributes(m);
                    if (a.Count > 0) sb.AppendLine($"  method {Format.Method(m, withModifiers: false)}  {string.Join(" ", a)}");
                }
            }
            sb.AppendLine();
        }
        var text = sb.ToString();
        if (!text.Contains('[', StringComparison.Ordinal) || !text.Contains('=', StringComparison.Ordinal))
            text += "No Il2Cpp attributes found. This tool needs a dummy DLL generated by Il2CppDumper or Cpp2IL (with attribute injection).";
        return pager.Page(text);
    }, cancellationToken);

    [McpServerTool(Name = "find_method_by_address", ReadOnly = true)]
    [Description("Map a native address from IDA/Ghidra/a crash log back to the managed method, using Il2Cpp [Address] attributes. Reports exact function starts, or the closest preceding method when the address is inside a function.")]
    public Task<string> FindMethodByAddress(
        [Description("Address in hex, as IDA/Ghidra show it: '0x1A2B3C', '1A2B3C', '1A2B3Ch' or '00000001`8001A2B3'. Prefix 'd:' for decimal.")] string address,
        [Description("Which attribute value to compare: rva, va, offset, or auto (all three).")] string kind = "auto",
        [Description(AssemblyDescription)] string? assembly = null,
        CancellationToken cancellationToken = default) => Read(workspace, () =>
    {
        var value = Il2CppService.ParseAddress(address) ?? throw new ToolError($"'{address}' is not a valid hex address.");
        var matches = il2cpp.FindByAddress(value, kind, workspace.Scope(assembly));
        if (matches.Count == 0) return $"No method found at or before 0x{value:X}.";
        var sb = new StringBuilder($"Address 0x{value:X}:\n");
        foreach (var m in matches)
            sb.AppendLine($"  [{m.Field.ToUpperInvariant()}] {m.Relation}: {Format.MemberLabel(m.Entry.Method)}  (start 0x{m.Start:X})  [{m.Entry.Assembly.Id}] {Format.Token(m.Entry.Method)}");
        return sb.ToString();
    }, cancellationToken);

    private static void AppendAttrs(StringBuilder sb, IHasCustomAttribute member, string indent)
    {
        foreach (var a in Il2CppService.GetAttributes(member))
            sb.AppendLine(indent + a);
    }
}
