using System.Text;
using System.Text.Json;
using dnlib.DotNet;
using NetDecompilerMcp.Core;
using static NetDecompilerMcp.Services.MetadataUtil;

namespace NetDecompilerMcp.Services;

/// <summary>
/// Exports Il2Cpp dummy-DLL metadata for native tools: an IDA Python script and a Ghidra script that create and name
/// every function and comment it with the managed signature, a C header with struct layouts at the dumped field offsets
/// (applied automatically by the IDA script), and an Il2CppDumper-style script.json.
/// </summary>
public sealed class Il2CppExporter(Il2CppService il2cpp)
{
    public sealed record ExportResult(List<string> Files, int Methods, int Structs);

    private sealed record MethodEntry(ulong Rva, string Name, string Signature);

    public ExportResult Export(IReadOnlyList<LoadedAssembly> scope, string outputDirectory, string formats, string baseName, CancellationToken ct)
    {
        var wanted = formats.Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries).Select(f => f.ToLowerInvariant()).ToHashSet();
        if (wanted.Contains("all")) wanted = ["ida", "ghidra", "header", "json"];
        foreach (var f in wanted.Where(f => f is not ("ida" or "ghidra" or "header" or "json")))
            throw new ToolError($"Unknown format '{f}'. Use ida, ghidra, header, json or all.");

        var methods = CollectMethods(scope, ct);
        if (methods.Count == 0)
            throw new ToolError("No Il2Cpp [Address] attributes in the selected assemblies. This needs Il2CppDumper/Cpp2IL dummy DLLs.");
        var dir = Path.GetFullPath(outputDirectory);
        Directory.CreateDirectory(dir);
        var files = new List<string>();
        int structs = 0;

        string? headerPath = null;
        if (wanted.Contains("header") || wanted.Contains("ida") || wanted.Contains("ghidra"))
        {
            var (header, count) = BuildHeader(scope, ct);
            structs = count;
            headerPath = Path.Combine(dir, baseName + ".h");
            File.WriteAllText(headerPath, header);
            files.Add(headerPath);
        }
        if (wanted.Contains("ida"))
            files.Add(Write(dir, baseName + "_ida.py", IdaScript(methods, Path.GetFileName(headerPath!))));
        if (wanted.Contains("ghidra"))
            files.Add(Write(dir, baseName + "_ghidra.py", GhidraScript(methods)));
        if (wanted.Contains("json"))
            files.Add(Write(dir, baseName + "_script.json", JsonSerializer.Serialize(new
            {
                ScriptMethod = methods.Select(m => new { Address = m.Rva, m.Name, m.Signature }),
            }, new JsonSerializerOptions { WriteIndented = true })));
        return new ExportResult(files, methods.Count, structs);
    }

    private static string Write(string dir, string name, string content)
    {
        var path = Path.Combine(dir, name);
        File.WriteAllText(path, content);
        return path;
    }

    // ------------------------------------------------------------------ methods

    private List<MethodEntry> CollectMethods(IReadOnlyList<LoadedAssembly> scope, CancellationToken ct)
    {
        var entries = new List<MethodEntry>();
        var used = new Dictionary<string, int>(StringComparer.Ordinal);
        foreach (var e in scope.SelectMany(il2cpp.GetIndex).Where(e => e.Rva != null).OrderBy(e => e.Rva))
        {
            ct.ThrowIfCancellationRequested();
            var name = $"{e.Method.DeclaringType.FullName.Replace('/', '.')}$${e.Method.Name}";
            // Overloads and shared generic bodies would collide: keep names unique (IDA/Ghidra reject duplicates).
            if (used.TryGetValue(name, out int n)) { used[name] = n + 1; name = $"{name}_{n + 1}"; }
            else used[name] = 0;
            entries.Add(new MethodEntry(e.Rva!.Value, name, $"{Format.Method(e.Method)}  [{e.Assembly.Id} {Format.Token(e.Method)}]"));
        }
        return entries;
    }

    private static string PyString(string s) => "\"" + s.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\n", " ") + "\"";

    private static string IdaScript(List<MethodEntry> methods, string headerFile)
    {
        var sb = new StringBuilder();
        sb.AppendLine("# IDA Python script generated by net-decompiler from Il2Cpp dummy DLLs.");
        sb.AppendLine("# File > Script file... (IDA 7.4+). Creates functions, names them Namespace.Type$$Method, comments signatures,");
        sb.AppendLine("# and imports the struct layouts from the header next to this script.");
        sb.AppendLine("import os");
        sb.AppendLine("import idaapi");
        sb.AppendLine("import idc");
        sb.AppendLine("import ida_funcs");
        sb.AppendLine();
        sb.AppendLine("METHODS = [");
        foreach (var m in methods)
            sb.AppendLine($"    (0x{m.Rva:X}, {PyString(m.Name)}, {PyString(m.Signature)}),");
        sb.AppendLine("]");
        sb.AppendLine($"HEADER = {PyString(headerFile)}");
        sb.AppendLine("""

            def apply():
                base = idaapi.get_imagebase()
                named = 0
                for rva, name, signature in METHODS:
                    ea = base + rva
                    if not ida_funcs.get_func(ea):
                        ida_funcs.add_func(ea)
                    if idc.set_name(ea, name, idc.SN_NOWARN | idc.SN_NOCHECK):
                        named += 1
                    idc.set_func_cmt(ea, signature, 0)
                header = os.path.join(os.path.dirname(os.path.abspath(__file__)), HEADER)
                errors = 0
                if os.path.exists(header):
                    with open(header) as f:
                        errors = idc.parse_decls(f.read(), idc.PT_SILENT)
                print("net-decompiler: named %d of %d functions; header import errors: %d" % (named, len(METHODS), errors))

            apply()
            """);
        return sb.ToString();
    }

    private static string GhidraScript(List<MethodEntry> methods)
    {
        var sb = new StringBuilder();
        sb.AppendLine("# Ghidra script generated by net-decompiler from Il2Cpp dummy DLLs (Jython or PyGhidra).");
        sb.AppendLine("# Creates functions, names them Namespace.Type$$Method and adds the managed signature as a plate comment.");
        sb.AppendLine("# For struct layouts, import the .h next to this script with File > Parse C Source.");
        sb.AppendLine("# @category net-decompiler");
        sb.AppendLine("from ghidra.program.model.symbol import SourceType");
        sb.AppendLine();
        sb.AppendLine("METHODS = [");
        foreach (var m in methods)
            sb.AppendLine($"    (0x{m.Rva:X}, {PyString(m.Name.Replace(' ', '_'))}, {PyString(m.Signature)}),");
        sb.AppendLine("]");
        sb.AppendLine("""

            def apply():
                base = currentProgram.getImageBase()
                functions = currentProgram.getFunctionManager()
                named = 0
                for rva, name, signature in METHODS:
                    addr = base.add(rva)
                    f = functions.getFunctionAt(addr)
                    if f is None:
                        f = createFunction(addr, None)
                    if f is not None:
                        try:
                            f.setName(name, SourceType.USER_DEFINED)
                            named += 1
                        except Exception:
                            pass
                    setPlateComment(addr, signature)
                print("net-decompiler: named %d of %d functions" % (named, len(METHODS)))

            apply()
            """);
        return sb.ToString();
    }

    // ------------------------------------------------------------------ structs

    private const string Prelude = """
        /* Struct layouts generated by net-decompiler from Il2Cpp dummy DLLs (field offsets as dumped). */
        /* Classes: absolute object offsets (klass and monitor header first). Value types: field-relative offsets. */
        typedef signed char nd_i8;
        typedef unsigned char nd_u8;
        typedef short nd_i16;
        typedef unsigned short nd_u16;
        typedef int nd_i32;
        typedef unsigned int nd_u32;
        typedef long long nd_i64;
        typedef unsigned long long nd_u64;
        typedef void* nd_ptr;

        """;

    private (string Header, int Count) BuildHeader(IReadOnlyList<LoadedAssembly> scope, CancellationToken ct)
    {
        var sb = new StringBuilder(Prelude);
        var emitted = new HashSet<TypeDef>();
        var names = new Dictionary<TypeDef, string>();
        var usedNames = new HashSet<string>(StringComparer.Ordinal);
        int count = 0;

        string CName(TypeDef t)
        {
            if (names.TryGetValue(t, out var n)) return n;
            var baseName = new string(t.FullName.Select(c => char.IsLetterOrDigit(c) ? c : '_').ToArray());
            var name = baseName;
            for (int i = 2; !usedNames.Add(name); i++) name = $"{baseName}_{i}";
            return names[t] = name;
        }

        void Emit(TypeDef t)
        {
            if (!emitted.Add(t)) return;
            var fields = InstanceFields(t);
            if (fields.Count == 0 && !t.IsValueType) return;
            // Value-type fields are embedded: declare those structs first.
            foreach (var (f, _) in fields)
                if (EmbeddedStruct(f.FieldType) is { } dep && dep != t) Emit(dep);

            var body = new StringBuilder();
            ulong position = 0;
            if (!t.IsValueType)
            {
                body.AppendLine("    nd_ptr klass;  /* 0x0 */");
                body.AppendLine("    nd_ptr monitor;  /* 0x8 */");
                position = 0x10;
            }
            int pad = 0;
            var members = new HashSet<string>(StringComparer.Ordinal) { "klass", "monitor" };
            foreach (var (f, offset) in fields.OrderBy(x => x.Offset))
            {
                if (offset < position) continue; // overlapping (explicit layout / union): keep the first
                if (offset > position) body.AppendLine($"    nd_u8 _pad{pad++}[0x{offset - position:X}];");
                var (ctype, size) = CType(f.FieldType, names, CName, emitted);
                // A derived class may redeclare a base field's name: C members must be unique.
                var member = Identifier(f.Name);
                if (!members.Add(member))
                {
                    member = $"{member}_{Identifier(Format.StripArity(f.DeclaringType.Name))}";
                    for (int i = 2; !members.Add(member); i++) member = $"{Identifier(f.Name)}_{i}";
                }
                body.AppendLine($"    {ctype} {member};  /* 0x{offset:X} {Format.Type(f.FieldType)} */");
                position = offset + size;
            }
            if (fields.Count == 0) body.AppendLine("    nd_u8 _empty;");
            sb.AppendLine($"/* {t.FullName} */");
            sb.AppendLine($"struct {CName(t)} {{");
            sb.Append(body);
            sb.AppendLine("};");
            sb.AppendLine();
            count++;
        }

        foreach (var t in scope.SelectMany(a => a.Module.GetTypes()))
        {
            ct.ThrowIfCancellationRequested();
            if (!t.IsEnum && !t.IsInterface && InstanceFields(t).Count > 0)
                Emit(t);
        }
        return (sb.ToString(), count);
    }

    /// <summary>Instance fields with dumped offsets, including inherited ones for classes.</summary>
    private static List<(FieldDef Field, ulong Offset)> InstanceFields(TypeDef t)
    {
        var list = new List<(FieldDef, ulong)>();
        var chain = new List<TypeDef>();
        for (var c = t; c != null && chain.Count < 32; c = t.IsValueType ? null : BaseTypeDef(c)) chain.Add(c);
        foreach (var c in chain)
            foreach (var f in c.Fields.Where(f => !f.IsStatic && !f.IsLiteral))
                if (OffsetOf(f) is { } offset)
                    list.Add((f, offset));
        return list;
    }

    private static ulong? OffsetOf(FieldDef f)
    {
        var attr = Il2CppService.GetAttributes(f).FirstOrDefault(a => a.Name == "FieldOffsetAttribute");
        return attr != null && attr.Values.TryGetValue("Offset", out var v) ? Il2CppService.ParseNumber(v) : null;
    }

    private static TypeDef? EmbeddedStruct(TypeSig sig)
    {
        if (sig is not ValueTypeSig vt || Try(() => vt.TypeDefOrRef.ResolveTypeDef()) is not { } td) return null;
        return td.IsEnum || td.Namespace == "System" && IsPrimitiveName(td.Name) ? null : td;
    }

    private static bool IsPrimitiveName(string name) =>
        name is "Boolean" or "Char" or "SByte" or "Byte" or "Int16" or "UInt16" or "Int32" or "UInt32" or "Int64" or "UInt64"
            or "Single" or "Double" or "IntPtr" or "UIntPtr";

    private static (string CType, ulong Size) CType(TypeSig sig, Dictionary<TypeDef, string> names, Func<TypeDef, string> cname, HashSet<TypeDef> emitted)
    {
        switch (sig.ElementType)
        {
            case ElementType.Boolean: case ElementType.U1: return ("nd_u8", 1);
            case ElementType.I1: return ("nd_i8", 1);
            case ElementType.Char: case ElementType.U2: return ("nd_u16", 2);
            case ElementType.I2: return ("nd_i16", 2);
            case ElementType.I4: return ("nd_i32", 4);
            case ElementType.U4: return ("nd_u32", 4);
            case ElementType.I8: return ("nd_i64", 8);
            case ElementType.U8: return ("nd_u64", 8);
            case ElementType.R4: return ("float", 4);
            case ElementType.R8: return ("double", 8);
            case ElementType.I: case ElementType.U: case ElementType.Ptr: case ElementType.FnPtr: return ("nd_ptr", 8);
        }
        if (sig is ValueTypeSig vt && Try(() => vt.TypeDefOrRef.ResolveTypeDef()) is { } td)
        {
            if (td.IsEnum && td.GetEnumUnderlyingType() is { } underlying)
                return CType(underlying, names, cname, emitted);
            if (td.Namespace == "System" && IsPrimitiveName(td.Name))
                return td.Name.String switch
                {
                    "Boolean" or "Byte" => ("nd_u8", 1), "SByte" => ("nd_i8", 1), "Char" or "UInt16" => ("nd_u16", 2), "Int16" => ("nd_i16", 2),
                    "Int32" => ("nd_i32", 4), "UInt32" => ("nd_u32", 4), "Int64" => ("nd_i64", 8), "UInt64" => ("nd_u64", 8),
                    "Single" => ("float", 4), "Double" => ("double", 8), _ => ("nd_ptr", 8),
                };
            if (emitted.Contains(td) && names.ContainsKey(td))
                return ($"struct {cname(td)}", StructSize(td));
            return ($"nd_u8 /* {td.Name} */", 1);
        }
        return ("nd_ptr", 8); // references: classes, strings, arrays, interfaces, delegates, generic instances
    }

    /// <summary>Size of a value type from its last dumped field (unknown tail padding is not included).</summary>
    private static ulong StructSize(TypeDef t)
    {
        var fields = InstanceFields(t);
        if (fields.Count == 0) return 1;
        var (last, offset) = fields.OrderBy(f => f.Offset).Last();
        ulong size = last.FieldType.ElementType switch
        {
            ElementType.Boolean or ElementType.U1 or ElementType.I1 => 1,
            ElementType.Char or ElementType.U2 or ElementType.I2 => 2,
            ElementType.I4 or ElementType.U4 or ElementType.R4 => 4,
            _ => 8,
        };
        if (EmbeddedStruct(last.FieldType) is { } inner && inner != t) size = StructSize(inner);
        return offset + size;
    }

    /// <summary>Microsoft-extension and C11 spellings that IDA's and MSVC-compatible parsers treat as keywords.</summary>
    private static readonly System.Text.RegularExpressions.Regex ReservedSpelling = new(
        "^_+(int8|int16|int32|int64|ptr32|ptr64|w64|asm|cdecl|stdcall|fastcall|thiscall|vectorcall|declspec|inline|forceinline|based|unaligned|restrict|" +
        "Bool|Complex|Imaginary|Alignas|Alignof|Atomic|Generic|Noreturn|Static_assert|Thread_local|far|near|huge|pascal|fortran|segment|self|try|except|finally|leave)$",
        System.Text.RegularExpressions.RegexOptions.Compiled);

    private static string Identifier(string name)
    {
        var s = new string(name.Select(c => char.IsLetterOrDigit(c) || c == '_' ? c : '_').ToArray());
        if (s.Length == 0 || char.IsDigit(s[0])) s = "_" + s;
        if (ReservedSpelling.IsMatch(s) || s.StartsWith("__", StringComparison.Ordinal)) s = "f" + s;
        return s is "int" or "char" or "float" or "double" or "long" or "short" or "struct" or "union" or "void" or "signed" or "unsigned"
            or "const" or "volatile" or "static" or "auto" or "register" or "extern" or "typedef" or "enum" or "return" or "if" or "else"
            or "for" or "while" or "do" or "switch" or "case" or "default" or "break" or "continue" or "goto" or "sizeof"
            ? s + "_" : s;
    }
}
