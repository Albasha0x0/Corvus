using System.Text;

namespace Corvus.Native.MachO;

/// <summary>
/// A class-dump style header from the Objective-C runtime metadata: named structures, protocols, classes with ivars,
/// class methods, instance methods with each property at its first accessor (the rest under "Remaining properties"),
/// and categories, in metadata order, with class-dump's type spellings. Swift types follow as comments.
/// </summary>
public static class ObjcHeader
{
    public static string Render(AppleObjcMetadata? objc, AppleSwiftMetadata? swift, string imageName)
    {
        var sb = new StringBuilder();
        sb.Append("//\n//     Generated by Corvus from ").Append(imageName).Append(" (Objective-C runtime metadata, class-dump layout).\n//\n\n");
        if (objc != null)
        {
            var structs = Structures(objc);
            if (structs.Count > 0)
            {
                sb.Append("#pragma mark Named Structures\n\n");
                foreach (var (name, fields) in structs)
                {
                    sb.Append("struct ").Append(name).Append(" {\n");
                    for (int i = 0; i < fields.Count; i++)
                        sb.Append("    ").Append(Declare(fields[i].Type, fields[i].Name ?? $"_field{i + 1}")).Append(";\n");
                    sb.Append("};\n\n");
                }
                sb.Append("#pragma mark -\n\n");
            }
            foreach (var p in objc.Protocols) Protocol(sb, p);
            foreach (var c in objc.Classes) Class(sb, c);
            foreach (var c in objc.Categories) Category(sb, c);
        }
        if (swift is { Types.Count: > 0 } or { Protocols.Count: > 0 }) Swift(sb, swift);
        return sb.ToString();
    }

    private static string Adopted(IReadOnlyList<string> protocols) => protocols.Count > 0 ? " <" + string.Join(", ", protocols) + ">" : "";

    private static void Protocol(StringBuilder sb, ObjcProtocol p)
    {
        sb.Append("@protocol ").Append(p.Name).Append(Adopted(p.Protocols)).Append('\n');
        foreach (var prop in p.Properties) sb.Append(Property(prop)).Append('\n');
        foreach (var m in p.Methods.Where(m => !m.Optional).OrderBy(m => m.IsClassMethod ? 0 : 1)) sb.Append(Method(m)).Append('\n');
        if (p.Methods.Any(m => m.Optional))
        {
            sb.Append("\n@optional\n");
            foreach (var m in p.Methods.Where(m => m.Optional).OrderBy(m => m.IsClassMethod ? 0 : 1)) sb.Append(Method(m)).Append('\n');
        }
        sb.Append("@end\n\n");
    }

    private static void Class(StringBuilder sb, ObjcClass c)
    {
        if (c.SwiftName != null) sb.Append("// Swift class ").Append(c.SwiftName).Append('\n');
        sb.Append("@interface ").Append(c.Name).Append(c.Superclass != null ? " : " + c.Superclass : "").Append(Adopted(c.Protocols)).Append('\n');
        if (c.Ivars.Count > 0)
        {
            sb.Append("{\n");
            foreach (var ivar in c.Ivars) sb.Append("    ").Append(Declare(Type(ivar.Type), ivar.Name)).Append(";\n");
            sb.Append("}\n");
        }
        Members(sb, c.Methods, c.Properties);
        sb.Append("@end\n\n");
    }

    private static void Category(StringBuilder sb, ObjcCategory c)
    {
        sb.Append("@interface ").Append(c.ClassName).Append(" (").Append(c.Name).Append(')').Append(Adopted(c.Protocols)).Append('\n');
        Members(sb, c.Methods, c.Properties);
        sb.Append("@end\n\n");
    }

    /// <summary>Class methods, then instance methods with a property in place of its first accessor, then the properties left.</summary>
    private static void Members(StringBuilder sb, IReadOnlyList<ObjcMethod> methods, IReadOnlyList<ObjcProperty> properties)
    {
        var lines = new List<string>();
        lines.AddRange(methods.Where(m => m.IsClassMethod).Select(Method));
        var accessors = new Dictionary<string, ObjcProperty>(StringComparer.Ordinal);
        foreach (var p in properties)
        {
            var (getter, setter) = Accessors(p);
            accessors.TryAdd(getter, p);
            if (setter != null) accessors.TryAdd(setter, p);
        }
        var shown = new HashSet<ObjcProperty>();
        foreach (var m in methods.Where(m => !m.IsClassMethod))
        {
            if (accessors.TryGetValue(m.Selector, out var p))
            {
                if (shown.Add(p)) lines.Add(Property(p));
            }
            else lines.Add(Method(m));
        }
        var rest = properties.Where(p => !shown.Contains(p)).ToList();
        if (lines.Count > 0 || rest.Count > 0) sb.Append('\n');
        foreach (var l in lines) sb.Append(l).Append('\n');
        if (rest.Count > 0)
        {
            sb.Append("\n// Remaining properties\n");
            foreach (var p in rest) sb.Append(Property(p)).Append('\n');
        }
        if (lines.Count > 0 || rest.Count > 0) sb.Append('\n');
    }

    private static (string Getter, string? Setter) Accessors(ObjcProperty p)
    {
        string getter = p.Name, setter = "set" + (p.Name.Length > 0 ? char.ToUpperInvariant(p.Name[0]) + p.Name[1..] : "") + ":";
        bool readOnly = false;
        foreach (var a in Attributes(p.Attributes))
            if (a.StartsWith('G')) getter = a[1..];
            else if (a.StartsWith('S')) setter = a[1..];
            else if (a == "R") readOnly = true;
        return (getter, readOnly ? null : setter);
    }

    /// <summary>Property attributes split at commas outside the quoted class name of the type.</summary>
    private static List<string> Attributes(string? attributes)
    {
        var list = new List<string>();
        if (string.IsNullOrEmpty(attributes)) return list;
        int start = 0;
        bool quoted = false;
        for (int i = 0; i <= attributes.Length; i++)
        {
            if (i < attributes.Length && attributes[i] == '"') quoted = !quoted;
            if (i == attributes.Length || (attributes[i] == ',' && !quoted))
            {
                list.Add(attributes[start..i]);
                start = i + 1;
            }
        }
        return list;
    }

    /// <summary>"@property(readonly, nonatomic) NSString *name; // @synthesize name=_name;" as class-dump writes it.</summary>
    internal static string Property(ObjcProperty p)
    {
        string type = "id";
        string? ivar = null;
        bool dynamic = false;
        var words = new List<string>();
        foreach (var a in Attributes(p.Attributes))
        {
            if (a.Length == 0) continue;
            switch (a[0])
            {
                case 'T': type = Type(a[1..]); break;
                case 'R': words.Add("readonly"); break;
                case 'C': words.Add("copy"); break;
                case '&': words.Add("retain"); break;
                case 'N': words.Add("nonatomic"); break;
                case 'W': words.Add("weak"); break;
                case 'G': words.Add("getter=" + a[1..]); break;
                case 'S': words.Add("setter=" + a[1..]); break;
                case 'D': dynamic = true; break;
                case 'V': ivar = a[1..]; break;
            }
        }
        var head = words.Count > 0 ? $"@property({string.Join(", ", words)}) " : "@property ";
        var tail = dynamic ? $" // @dynamic {p.Name};" : ivar is { Length: > 0 } v ? $" // @synthesize {p.Name}{(v != p.Name ? "=" + v : "")};" : "";
        return head + Declare(type, p.Name) + ";" + tail;
    }

    /// <summary>"- (void)setName:(id)arg1 age:(int)arg2;" from the selector and its type encoding.</summary>
    internal static string Method(ObjcMethod m)
    {
        var prefix = m.IsClassMethod ? "+ " : "- ";
        var types = ObjcTypeEncoding.MethodTypes(m.Types);
        if (types == null || types.Count < 3) return $"{prefix}(id){Selector(m.Selector, null)}; // types not read: {m.Types}";
        return $"{prefix}({Type(types[0])}){Selector(m.Selector, types)};";
    }

    private static string Selector(string selector, List<string>? types)
    {
        if (!selector.Contains(':', StringComparison.Ordinal)) return selector;
        var parts = selector.Split(':');
        var sb = new StringBuilder();
        for (int i = 0; i < parts.Length - 1; i++)
        {
            if (i > 0) sb.Append(' ');
            var arg = types != null && i + 3 < types.Count ? Type(types[i + 3]) : "id";
            sb.Append(parts[i]).Append(":(").Append(arg).Append(")arg").Append(i + 1);
        }
        return sb.ToString();
    }

    /// <summary>A type encoding in class-dump's spelling.</summary>
    internal static string Type(string? encoding)
    {
        var c = ObjcTypeEncoding.ToC(encoding);
        return c switch
        {
            "bool" => "_Bool",
            "int32_t" => "long",
            "uint32_t" => "unsigned long",
            "id /* block */" => "CDUnknownBlockType",
            "void /* unknown */ *" => "CDUnknownFunctionPointerType",
            _ => c,
        };
    }

    /// <summary>A declaration of <paramref name="name"/> with a C type: "char name[4]", "unsigned int name:3", "NSString *name", "int name".</summary>
    internal static string Declare(string type, string name)
    {
        if (type.EndsWith(']') && type.LastIndexOf('[') is var open and > 0) return $"{type[..open]} {name}{type[open..]}";
        if (type.StartsWith("unsigned int : ", StringComparison.Ordinal)) return $"unsigned int {name}:{type[15..]}";
        return type.EndsWith('*') ? type + name : $"{type} {name}";
    }

    /// <summary>Named structures with members in any encoding of the metadata, first body seen per name.</summary>
    private static List<(string Name, List<(string Type, string? Name)> Fields)> Structures(AppleObjcMetadata objc)
    {
        var found = new List<(string, List<(string, string?)>)>();
        var seen = new HashSet<string>(StringComparer.Ordinal);
        var encodings = objc.Classes.SelectMany(c => c.Ivars.Select(i => i.Type).Concat(c.Methods.Select(m => m.Types)).Concat(c.Properties.Select(p => p.Attributes)))
            .Concat(objc.Categories.SelectMany(c => c.Methods.Select(m => m.Types).Concat(c.Properties.Select(p => p.Attributes))))
            .Concat(objc.Protocols.SelectMany(p => p.Methods.Select(m => m.Types)));
        foreach (var e in encodings)
        {
            if (string.IsNullOrEmpty(e)) continue;
            for (int i = e.IndexOf('{'); i >= 0 && i < e.Length; i = e.IndexOf('{', i + 1))
            {
                int eq = e.IndexOf('=', i), end = ObjcTypeEncoding.TypeEnd(e, i);
                if (eq < 0 || end < 0 || eq > end) continue;
                var name = e[(i + 1)..eq];
                if (name is "" or "?" || !seen.Add(name)) continue;
                var fields = new List<(string, string?)>();
                for (int at = eq + 1; at < end - 1;)
                {
                    string? fieldName = null;
                    if (e[at] == '"' && e.IndexOf('"', at + 1) is var q and > 0) { fieldName = e[(at + 1)..q]; at = q + 1; }
                    int next = ObjcTypeEncoding.TypeEnd(e, at);
                    if (next < 0 || next > end - 1) { fields.Clear(); break; }
                    fields.Add((Type(e[at..next]), fieldName));
                    at = next;
                }
                if (fields.Count > 0) found.Add((name, fields));
                else seen.Remove(name);
            }
        }
        return found;
    }

    private static void Swift(StringBuilder sb, AppleSwiftMetadata swift)
    {
        sb.Append("#pragma mark Swift types\n\n");
        foreach (var t in swift.Types)
        {
            sb.Append("// ").Append(t.Kind).Append(' ').Append(t.Name).Append(t.Superclass != null ? " : " + t.Superclass : "");
            var conformances = swift.Conformances.Where(c => c.Type == t.Name).Select(c => c.Protocol).ToList();
            if (conformances.Count > 0) sb.Append(t.Superclass != null ? ", " : " : ").Append(string.Join(", ", conformances));
            sb.Append(" {\n");
            foreach (var f in t.Fields)
                sb.Append("//     ").Append(t.Kind == "enum" ? "case " + f.Name + (f.Type != null ? $"({f.Type})" : "") : $"{(f.IsVar ? "var" : "let")} {f.Name}: {f.Type ?? "?"}").Append('\n');
            sb.Append("// }\n\n");
        }
        foreach (var p in swift.Protocols) sb.Append("// protocol ").Append(p.Name).Append("\n\n");
    }
}
